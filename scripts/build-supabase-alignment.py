"""Generate an additive migration from the verified, local Supabase exports."""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKUP = ROOT / 'db-backups/alignment-2026-10-09'
SCHEMA = {r['object_name']: r for r in csv.DictReader((BACKUP / 'old-schema.csv').open())}
INVENTORY = json.loads((BACKUP / 'public-api-inventory.json').read_text())['results']

def ident(value):
    return '"' + value.replace('"', '""') + '"'

def literal(value):
    if value is None: return 'NULL'
    if isinstance(value, bool): return 'true' if value else 'false'
    if isinstance(value, (int, float)): return str(value)
    if isinstance(value, (dict, list)): value = json.dumps(value, ensure_ascii=False)
    return "'" + str(value).replace("'", "''") + "'"

sql = ["-- Recover missing BMW catalog data while preserving current data and views.",
       "-- Source: restored nfnamdmdavbaedpesdpy; target: current reboxjzkoopkfwaemjrz.",
       "-- No account or garage data is included in this public migration.",
       'begin;', 'set local search_path = public, pg_catalog;']
meta = json.loads(SCHEMA['public.bmw_configuration_differentials']['definition'])
columns = []
for c in meta['columns']:
    definition = ident(c['name']) + ' ' + c['type']
    if c['default'] and c['default'].startswith('nextval('):
        definition += ' generated by default as identity'
    elif c['default']:
        definition += ' default ' + c['default']
    if c['not_null']: definition += ' not null'
    columns.append(definition)
columns += ['constraint ' + ident(c['name']) + ' ' + c['definition'] for c in meta['constraints']]
sql += ['create table if not exists public.bmw_configuration_differentials (\n  ' + ',\n  '.join(columns) + '\n);']
rows = json.loads((BACKUP / 'bmw_configuration_differentials.json').read_text())
keys = [c['name'] for c in meta['columns']]
# Reject missing parent configurations rather than silently skipping data.
sql += ["do $check$ begin if exists (select 1 from (values " + ','.join('('+str(i)+')' for i in sorted({r['configuration_id'] for r in rows})) + ") as incoming(id) left join public.bmw_variant_configurations c on c.id=incoming.id where c.id is null) then raise exception 'Alignment requires missing parent BMW configurations'; end if; end $check$;"]
for start in range(0, len(rows), 250):
    values = ',\n'.join('(' + ', '.join(literal(r.get(k)) for k in keys) + ')' for r in rows[start:start+250])
    sql += ['insert into public.bmw_configuration_differentials (' + ', '.join(map(ident, keys)) + ') values\n' + values + '\non conflict (id) do nothing;']
sql += ["select setval(pg_get_serial_sequence('public.bmw_configuration_differentials','id'), greatest(coalesce((select max(id) from public.bmw_configuration_differentials),1), (select last_value from public.bmw_configuration_differentials_id_seq)), true);",
        'alter table public.bmw_configuration_differentials enable row level security;',
        "do $policy$ begin if not exists (select 1 from pg_policies where schemaname='public' and tablename='bmw_configuration_differentials' and policyname='BMW differential catalog read') then create policy \"BMW differential catalog read\" on public.bmw_configuration_differentials for select to anon, authenticated using (true); end if; end $policy$;",
        'grant select on public.bmw_configuration_differentials to anon, authenticated;']

for name in ['bmw_chassis_selector','bmw_variant_lookup','bmw_configuration_differential_lookup']:
    definition = SCHEMA['public.'+name]['definition'].strip().rstrip(';')
    sql += [f"do $missing$ begin if to_regclass('public.{name}') is null then execute $view$create view public.{name} with (security_invoker=true) as {definition}$view$; end if; end $missing$;",
            f'grant select on public.{name} to anon, authenticated;']

# Keep every current column and its order. Existing non-null values win; recovered
# rows only enter when the vehicle/configuration key is absent. A stored marker
# keeps repeated application from nesting the existing view definition again.
raw_specs = SCHEMA['public.bmw_technical_specs']['definition'].strip().rstrip(';')
for name in ['bmw_configuration_lookup','bmw_technical_specs','bmw_dropdown_catalog']:
    is_dropdown = name == 'bmw_dropdown_catalog'
    source = SCHEMA['public.'+name]['definition'].strip().rstrip(';') if is_dropdown else raw_specs
    sample = json.loads((BACKUP / f'restored-public-data/{name}.json').read_text())[0]
    # configuration_lookup uses the technical-spec source, including columns not
    # exposed by the legacy projection; don't add those unnecessary columns.
    source_names = list(sample)
    source_array = 'array[' + ','.join(literal(x) for x in source_names) + ']::text[]'
    key = 'c.item_type=s.item_type and c.model_id=s.model_id and c.generation_id is not distinct from s.generation_id' if is_dropdown else 'c.variant_id=s.variant_id and c.configuration_id is not distinct from s.configuration_id'
    enrich = 'false' if is_dropdown else 'true'
    sql += [f"""do $align$
+declare original text; recovered text := $source${source}$source$;
+  source_columns text[] := {source_array};
+  current_columns text[]; current_projection text; recovered_projection text;
+  column_info record; column_name text; marker text := 'garage-alignment-020';
+begin
+  if obj_description('public.{name}'::regclass, 'pg_class') = marker then return; end if;
+  original := rtrim(pg_get_viewdef('public.{name}'::regclass, true), E'; \\n');
+  current_columns := array[]::text[];
+  for column_info in select attname, format_type(atttypid,atttypmod) as sql_type from pg_attribute where attrelid='public.{name}'::regclass and attnum>0 and not attisdropped order by attnum loop
+    column_name := column_info.attname;
+    current_columns := array_append(current_columns, column_name);
+    current_projection := concat_ws(', ', current_projection,
+      case when {enrich} and column_name=any(source_columns) then format('coalesce(c.%I,s.%I) as %I',column_name,column_name,column_name) else format('c.%I',column_name) end);
+    recovered_projection := concat_ws(', ', recovered_projection,
+      case when column_name=any(source_columns) then format('s.%I',column_name) else format('null::%s as %I',column_info.sql_type,column_name) end);
+  end loop;
+  foreach column_name in array source_columns loop
+    if not column_name=any(current_columns) then
+      current_projection := concat_ws(', ',current_projection,format('s.%I',column_name));
+      recovered_projection := concat_ws(', ',recovered_projection,format('s.%I',column_name));
+    end if;
+  end loop;
+  execute format('create or replace view public.{name} as with existing as (%s), recovered as (%s) select %s from existing c left join recovered s on {key} union all select %s from recovered s where not exists (select 1 from existing c where {key})',original,recovered,current_projection,recovered_projection);
+  comment on view public.{name} is 'garage-alignment-020';
+end $align$;""".replace('\n+','\n')]

sql += ["notify pgrst, 'reload schema';", 'commit;']
out = ROOT / 'supabase/migrations/020_restore_missing_bmw_catalog.sql'
out.write_text('\n\n'.join(sql)+'\n')
# Private, local-only recovery: map the donor account to the target account by
# email and add only missing vehicle identities, keeping existing cars intact.
raw = (BACKUP / 'old-user-saved-vehicles.sql').read_text().replace('INSERT INTO public.user_saved_vehicles', 'INSERT INTO recovered_garage')
owner = json.loads((BACKUP/'garage_owner.json').read_text())[0]
private = f"""begin;
create temporary table recovered_garage (like public.user_saved_vehicles including defaults) on commit drop;
{raw}
do $owner$ begin if (select count(*) from auth.users where lower(email)=lower({literal(owner['email'])})) <> 1 then raise exception 'Sign up the garage owner in the current project before importing'; end if; end $owner$;
update recovered_garage set user_id=(select id from auth.users where lower(email)=lower({literal(owner['email'])}));
insert into public.user_saved_vehicles
select r.* from (
  select distinct on (user_id,brand,model,engine,body_type,catalog_variant_id,catalog_configuration_id) * from recovered_garage
  order by user_id,brand,model,engine,body_type,catalog_variant_id,catalog_configuration_id,updated_at desc,created_at desc
) r where not exists (
  select 1 from public.user_saved_vehicles c where c.user_id=r.user_id
  and c.brand=r.brand and c.model is not distinct from r.model and c.engine is not distinct from r.engine
  and c.body_type is not distinct from r.body_type
  and coalesce(c.catalog_variant_id,c.bmw_variant_id) is not distinct from coalesce(r.catalog_variant_id,r.bmw_variant_id)
  and coalesce(c.catalog_configuration_id,c.bmw_configuration_id) is not distinct from coalesce(r.catalog_configuration_id,r.bmw_configuration_id)
) on conflict (id) do nothing;
commit;
"""
(BACKUP/'restore-private-garage.sql').write_text(private)
# The validator consumes JSON instead of requiring a CSV parser in Node.
(BACKUP/'old-schema.json').write_text(json.dumps(list(SCHEMA.values()),indent=2)+'\n')
print(out.relative_to(ROOT),len(rows),'differential rows')
print('Private recovery saved under ignored db-backups/')
