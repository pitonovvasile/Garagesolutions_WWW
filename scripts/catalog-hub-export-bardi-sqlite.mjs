#!/usr/bin/env node
/**
 * Export the local GarageSolutions_Configurator SQLite prototype into SQL
 * statements for catalog_hub supplier evidence tables.
 *
 * Usage:
 *   node scripts/catalog-hub-export-bardi-sqlite.mjs \
 *     --db /Users/vasilepitonov/Desktop/GarageSolutions_Configurator/data/catalog.sqlite3 \
 *     --out /tmp/bardi-catalog-hub-import.sql
 *
 * The generated SQL imports supplier-side Bardi vehicle types, years and
 * engine refs. It does not write canonical vehicle/product rows.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

const DEFAULT_DB =
  "/Users/vasilepitonov/Desktop/GarageSolutions_Configurator/data/catalog.sqlite3";

function argValue(name, fallback = null) {
  const idx = process.argv.indexOf(name);
  if (idx === -1) return fallback;
  return process.argv[idx + 1] ?? fallback;
}

function hasArg(name) {
  return process.argv.includes(name);
}

const dbPath = argValue("--db", DEFAULT_DB);
const outPath = argValue("--out", null);
const summaryOnly = hasArg("--summary");

function sqliteJson(sql) {
  const raw = execFileSync("sqlite3", ["-json", dbPath, sql], {
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  }).trim();
  return raw ? JSON.parse(raw) : [];
}

function q(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function qText(value) {
  return q(value ?? "");
}

function n(value) {
  if (value === null || value === undefined || value === "") return "null";
  const num = Number(value);
  return Number.isFinite(num) ? String(num) : "null";
}

function json(value) {
  return `${q(JSON.stringify(value ?? {}))}::jsonb`;
}

function normalizeModelLabel(row) {
  const model = String(row.model ?? "").trim();
  const generation = String(row.generation ?? "").trim();
  const from = Number(row.year_from || 0);
  const to = Number(row.year_to || 0);
  if (!from) return model;
  return `${model}${generation ? ` (${generation})` : ""} ${from} - ${to || ""}`.trim();
}

function engineLabel(row) {
  const displacement = Number(row.displacement_l || 0);
  const fuel = String(row.fuel || "unknown").trim() || "unknown";
  if (!displacement) return fuel;
  return `${displacement.toFixed(1)} - ${fuel}`;
}

function statementHeader({ makes, types, years, variants }) {
  const contentHash = createHash("sha256")
    .update(JSON.stringify({ makes, types, years, variants }))
    .digest("hex");

  return [
    "-- Generated by scripts/catalog-hub-export-bardi-sqlite.mjs",
    `-- Source SQLite: ${dbPath}`,
    `-- Counts: ${makes.length} makes, ${types.length} vehicle types, ${years.length} years, ${variants.length} vehicle refs`,
    "begin;",
    "",
    "insert into catalog_hub.suppliers as s (",
    "  id, name, kind, website_url, integration_status, settings",
    ")",
    "values (",
    "  'bardi',",
    "  'Bardi Auto',",
    "  'parts_distributor',",
    "  'https://www.bardiauto.ro',",
    "  'selector_snapshot',",
    `  jsonb_build_object('source', 'local_sqlite_export', 'source_hash', ${q(contentHash)})`,
    ")",
    "on conflict (id) do update set",
    "  name = excluded.name,",
    "  kind = excluded.kind,",
    "  website_url = excluded.website_url,",
    "  integration_status = excluded.integration_status,",
    "  settings = s.settings || excluded.settings,",
    "  updated_at = now();",
    "",
  ].join("\n");
}

function valuesInsert(table, columns, rows, conflictSql) {
  if (!rows.length) return "";
  const chunks = [];
  const chunkSize = 500;
  for (let i = 0; i < rows.length; i += chunkSize) {
    const slice = rows.slice(i, i + chunkSize);
    chunks.push(
      [
        `insert into ${table} (${columns.join(", ")})`,
        "values",
        slice.map((row) => `  (${row.join(", ")})`).join(",\n"),
        conflictSql,
        "",
      ].join("\n")
    );
  }
  return chunks.join("\n");
}

const makes = sqliteJson("select id, name from makes order by id");
const types = sqliteJson(`
  select
    t.id,
    m.name as make,
    t.model,
    t.generation,
    t.year_from,
    t.year_to
  from vehicle_types t
  join makes m on m.id = t.make_id
  order by t.id
`);
const years = sqliteJson(`
  select
    y.type_id,
    y.year,
    coalesce(o.review_status, 'unreviewed') as review_status,
    coalesce(o.review_reason, '') as review_reason
  from vehicle_years y
  left join source_year_observations o
    on o.supplier_id = 'bardi'
   and o.type_id = y.type_id
   and o.year = y.year
  order by y.type_id, y.year
`);
const variants = sqliteJson(`
  select
    v.id,
    v.type_id,
    v.year,
    v.displacement_l,
    v.fuel,
    v.engine_code,
    coalesce(o.review_status, 'unreviewed') as review_status
  from vehicle_variants v
  left join source_engine_observations o
    on o.supplier_id = 'bardi'
   and o.type_id = v.type_id
   and o.year = v.year
   and (
      o.engine_label = printf('%.1f - %s', v.displacement_l, v.fuel)
      or o.engine_label = v.fuel
   )
  order by v.type_id, v.year, v.id
`);

if (summaryOnly) {
  const byMake = sqliteJson(`
    select
      m.name,
      count(distinct t.id) as vehicle_types,
      count(distinct y.type_id || ':' || y.year) as model_years,
      count(distinct v.id) as vehicle_refs
    from makes m
    left join vehicle_types t on t.make_id = m.id
    left join vehicle_years y on y.type_id = t.id
    left join vehicle_variants v on v.type_id = t.id
    group by m.id, m.name
    order by m.name
  `);
  console.log(
    JSON.stringify(
      {
        dbPath,
        totals: {
          makes: makes.length,
          vehicleTypes: types.length,
          modelYears: years.length,
          vehicleRefs: variants.length,
        },
        sample: byMake.filter((row) =>
          ["BARDI", "BMW", "FORD", "MERCEDES BENZ", "AUDI"].includes(row.name)
        ),
      },
      null,
      2
    )
  );
  process.exit(0);
}

const typeRows = types.map((row) => [
  "'bardi'",
  qText(`sqlite-type:${row.id}`),
  qText(row.make),
  qText(row.model),
  qText(row.generation),
  n(row.year_from || null),
  n(row.year_to || null),
  "null",
  "'unmatched'",
  "0",
  json({
    sqlite_type_id: row.id,
    make: row.make,
    model: row.model,
    generation: row.generation,
    model_label: normalizeModelLabel(row),
  }),
]);

const yearRows = years.map((row) => [
  "'bardi'",
  qText(`sqlite-type:${row.type_id}`),
  n(row.year),
  qText(row.review_status),
  qText(row.review_reason),
  json({ sqlite_type_id: row.type_id, year: row.year }),
]);

const variantRows = variants.map((row) => {
  const label = engineLabel(row);
  return [
    "'bardi'",
    qText(`sqlite-variant:${row.id}`),
    qText(`sqlite-type:${row.type_id}`),
    n(row.year),
    qText(label),
    qText(row.engine_code),
    n(row.displacement_l || null),
    qText(row.fuel || "unknown"),
    "'unmatched'",
    "0",
    qText(row.review_status),
    json({
      sqlite_variant_id: row.id,
      sqlite_type_id: row.type_id,
      year: row.year,
      displacement_l: row.displacement_l,
      fuel: row.fuel,
      engine_code: row.engine_code,
      engine_label: label,
    }),
  ];
});

const sql = [
  statementHeader({ makes, types, years, variants }),
  valuesInsert(
    "catalog_hub.supplier_vehicle_types",
    [
      "supplier_id",
      "external_type_id",
      "external_make_label",
      "external_model_label",
      "external_generation_label",
      "external_year_from",
      "external_year_to",
      "source_url",
      "match_status",
      "match_confidence",
      "raw_payload",
    ],
    typeRows,
    [
      "on conflict (supplier_id, external_type_id) do update set",
      "  external_make_label = excluded.external_make_label,",
      "  external_model_label = excluded.external_model_label,",
      "  external_generation_label = excluded.external_generation_label,",
      "  external_year_from = excluded.external_year_from,",
      "  external_year_to = excluded.external_year_to,",
      "  raw_payload = excluded.raw_payload,",
      "  updated_at = now();",
    ].join("\n")
  ),
  valuesInsert(
    "catalog_hub.supplier_vehicle_years",
    [
      "supplier_id",
      "external_type_id",
      "production_year",
      "review_status",
      "review_reason",
      "raw_payload",
    ],
    yearRows,
    [
      "on conflict (supplier_id, external_type_id, production_year) do update set",
      "  review_status = excluded.review_status,",
      "  review_reason = excluded.review_reason,",
      "  raw_payload = excluded.raw_payload,",
      "  updated_at = now();",
    ].join("\n")
  ),
  valuesInsert(
    "catalog_hub.supplier_vehicle_refs",
    [
      "supplier_id",
      "external_vehicle_id",
      "external_type_id",
      "production_year",
      "external_engine_label",
      "external_engine_code",
      "displacement_l",
      "fuel_type",
      "match_status",
      "match_confidence",
      "review_status",
      "raw_payload",
    ],
    variantRows,
    [
      "on conflict (supplier_id, external_vehicle_id) do update set",
      "  external_type_id = excluded.external_type_id,",
      "  production_year = excluded.production_year,",
      "  external_engine_label = excluded.external_engine_label,",
      "  external_engine_code = excluded.external_engine_code,",
      "  displacement_l = excluded.displacement_l,",
      "  fuel_type = excluded.fuel_type,",
      "  review_status = excluded.review_status,",
      "  raw_payload = excluded.raw_payload,",
      "  updated_at = now();",
    ].join("\n")
  ),
  "commit;",
  "",
].join("\n");

if (outPath) {
  writeFileSync(outPath, sql, "utf8");
  console.log(`Wrote ${outPath}`);
} else {
  process.stdout.write(sql);
}
